#!/usr/bin/env python3
"""Step 12: recreate data/tables/sealed_results.csv from the holdout run table.

Committed after unsealing (see PREREGISTRATION.md). Calls only the pipeline
functions frozen at tag eval-v1 (src/step4b_model.py: fit_glm, standardise,
and its REF_FLOW/B/SEED/TREATMENT constants), unchanged. The committed
sealed_results.csv is never regenerated by the test suite; running this
script as __main__ writes the recreated table to a sibling check file only.
Run: uv run python src/step12_holdout_eval.py
"""
import sys
from pathlib import Path
import numpy as np
import pandas as pd
from scipy import stats as _sstats
sys.path.insert(0, str(Path(__file__).parent))
import step4b_model as frozen

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "data" / "tables"


def recreate_sealed_results(tables: Path = TABLES) -> pd.DataFrame:
    """Apply the frozen eval-v1 pipeline to per_run_holdout.csv, in memory."""
    runs = pd.read_csv(tables / "per_run_holdout.csv").dropna(subset=["frac_health1"]).copy()
    model, patients, use_logflow, _aics = frozen.fit_glm(runs)
    runs = frozen.standardise(runs, model, patients, use_logflow)
    rng = np.random.default_rng(frozen.SEED)
    visit_stats = {}
    for (patient, date, visit), g in runs.groupby(["patient", "date", "visit"]):
        point = float(np.average(g.frac_adj, weights=g.n_kept))
        boots = []
        arr_f, arr_n = g.frac_adj.values, g.n_kept.values
        for _ in range(frozen.B):
            idx = rng.integers(0, len(g), len(g))
            boots.append(float(np.average(arr_f[idx], weights=arr_n[idx])))
        visit_stats[(patient, str(date))] = {
            "patient": patient, "date": str(date), "visit": visit, "frac_adj": point,
            "var": float(np.var(boots, ddof=1)), "n_kept": int(g.n_kept.sum()),
            "n_runs": int(len(g)), "skip_rate": float(g.skip_rate.mean())}
    visits = pd.DataFrame(visit_stats.values()).sort_values(["patient", "date"])
    raw = pd.read_csv(tables / "per_visit_holdout.csv")
    raw_map = {(r.patient, str(r.date)): (float(r.frac_health1), int(r.n_kept)) for r in raw.itertuples()}
    out = []
    for patient, g in visits.groupby("patient"):
        g = g.reset_index(drop=True)
        for i in range(len(g) - 1):
            a, b = g.iloc[i], g.iloc[i + 1]
            mult = float(_sstats.t.ppf(0.975, max(a.n_runs + b.n_runs - 2, 1)))
            rcv = mult * np.sqrt(a["var"] + b["var"])
            (pa, na), (pb, nb) = raw_map[(patient, a.date)], raw_map[(patient, b.date)]
            delta_raw, delta_adj = pb - pa, b.frac_adj - a.frac_adj
            pooled = (pa * na + pb * nb) / (na + nb)
            band = 1.96 * np.sqrt(pooled * (1 - pooled) * (1 / na + 1 / nb))
            qc = (a.skip_rate > 0.25) or (b.skip_rate > 0.25) or (a.n_kept < 500) or (b.n_kept < 500)
            ctx = frozen.TREATMENT[patient] + (" initiation (from day-0 baseline)" if i == 0 else " on-treatment")
            out.append({"patient": patient, "from": a.visit, "to": b.visit, "treatment": ctx,
                        "delta_raw": round(float(delta_raw), 4), "delta_adj": round(float(delta_adj), 4),
                        "RCV95": round(float(rcv), 4),
                        "decision": "indeterminate_QC" if qc else ("exceeds_RCV" if abs(delta_adj) > rcv else "within_RCV"),
                        "naive_decision": "exceeds_RCV" if abs(delta_raw) > band else "within_RCV",
                        "from_skip_rate": round(float(a.skip_rate), 4), "to_skip_rate": round(float(b.skip_rate), 4)})
    return pd.DataFrame(out)


if __name__ == "__main__":
    got = recreate_sealed_results()
    dest = TABLES / "sealed_results_recreated_check.csv"
    got.to_csv(dest, index=False)
    print(got.to_string(index=False))
    print(f"wrote check file (committed sealed_results.csv untouched): {dest}")
